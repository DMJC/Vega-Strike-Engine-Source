#ifndef VEGA_STRIKE_ENGINE_GLDRV_GL_PRIMITIVES_H
#define VEGA_STRIKE_ENGINE_GLDRV_GL_PRIMITIVES_H

/**
 * Converts the engine's primitive types (POLYTYPE) into draws a core
 * profile accepts. GL_QUADS, GL_QUAD_STRIP and GL_POLYGON are gone from
 * core, so:
 *  - quads are expanded into indexed triangle pairs (v0 v1 v2, v0 v2 v3),
 *  - quad strips are drawn as triangle strips (they rasterize identically),
 *  - polygons are drawn as triangle fans (the engine only uses convex ones).
 *
 * Nothing here talks to OpenGL.
 */

#include <cstddef>
#include <cstdint>
#include <vector>

namespace vsgl {

/// Mirrors the POLYTYPE enum in gfxlib_struct.h (checked with static_asserts there)
enum class PolyType {
    Tri = 0,
    Quad,
    Line,
    TriStrip,
    QuadStrip,
    TriFan,
    LineStrip,
    Poly,
    Point,
};

/// The primitive types that survive into core profiles
enum class Primitive {
    Points,
    Lines,
    LineStrip,
    Triangles,
    TriangleStrip,
    TriangleFan,
};

struct PrimitiveMapping {
    Primitive primitive;
    bool expand_quads;  ///< needs indices generated by AppendQuadIndices
};

PrimitiveMapping MapPolyType(PolyType type);

/// GLenum for a core primitive (GL_TRIANGLES, ...)
unsigned int PrimitiveToGL(Primitive primitive);

/**
 * How many of `count` vertices a primitive actually consumes; the rest are
 * dropped, as GL drops incomplete primitives. Applied after quad strips have
 * become triangle strips, since a triangle strip would otherwise draw one
 * triangle more than the quad strip did.
 */
uint32_t UsableVertexCount(PolyType type, uint32_t count);

/// Number of triangle indices `count` quad vertices expand to
inline uint32_t QuadIndexCount(uint32_t count) {
    return (count / 4) * 6;
}

/// Appends triangle indices for `count` quad vertices starting at `first`
void AppendQuadIndices(uint32_t first, uint32_t count, std::vector<uint32_t> &out);

/// Appends triangle indices for `count` quad corners read from an index array
void AppendQuadIndices(const void *indices, int index_size, uint32_t first, uint32_t count,
        std::vector<uint32_t> &out);

/// Reads one index of size 1, 2 or 4 bytes
uint32_t ReadIndex(const void *indices, int index_size, size_t i);

struct DrawCommand {
    Primitive primitive;
    bool indexed;
    /// Index size in bytes (1, 2, 4) when indexed
    int index_size;
    /// First vertex (arrays) or first index element (elements)
    uint32_t first;
    uint32_t count;
};

/**
 * Everything needed to draw a multi-list vertex list on a core profile.
 *
 * Whenever `indices` is non-empty, every indexed command refers to it
 * (32-bit indices). For a list that had indices of its own this is a
 * rebuilt copy that replaces them (`rebuilt_indices`); for a non-indexed
 * list it holds the generated quad indices. When `indices` is empty, the
 * indexed commands refer to the list's original index array.
 */
struct DrawPlan {
    std::vector<DrawCommand> commands;
    std::vector<uint32_t> indices;
    bool rebuilt_indices = false;
};

/**
 * @param types      primitive type of each list
 * @param counts     vertex (or index) count of each list
 * @param num_lists  number of lists
 * @param indices    the list's index array, or nullptr for non-indexed lists
 * @param index_size 1, 2 or 4; ignored when indices is nullptr
 *
 * Consecutive lists of independent primitives (triangles, lines, points)
 * that end up contiguous are merged into a single command.
 */
DrawPlan BuildDrawPlan(const PolyType *types, const int *counts, int num_lists,
        const void *indices, int index_size);

/// Alignment of every allocation in the streaming vertex/index buffers
const size_t kStreamAlignment = 16;

/// Rounds a streaming allocation up to kStreamAlignment
inline size_t StreamAlign(size_t bytes) {
    return (bytes + kStreamAlignment - 1) & ~(kStreamAlignment - 1);
}

/**
 * Size of each fenced region of a persistently mapped streaming ring, rounded
 * down so every region starts aligned (index offsets must be multiples of the
 * index size, so capacity / regions alone is not good enough).
 */
inline size_t StreamRingRegionSize(size_t capacity, size_t regions) {
    return (capacity / regions) & ~(kStreamAlignment - 1);
}

/// Interleaved float layout used by GFXDraw: position, color, texcoord0, texcoord1
struct InterleavedLayout {
    int stride_bytes;
    int position_offset, position_size;
    int color_offset, color_size;
    int tex0_offset, tex0_size;
    int tex1_offset, tex1_size;
};

InterleavedLayout ComputeInterleavedLayout(int vsize, int csize, int tsize0, int tsize1);

} // namespace vsgl

#endif //VEGA_STRIKE_ENGINE_GLDRV_GL_PRIMITIVES_H
